async function requireEmptyDatabase(client: Pick<PoolClient, "query">) {
  const current = await client.query<{ database: string }>(
    "SELECT current_database() AS database",
  );
  if (current.rows[0]?.database !== ANDROID_STAGING_SEED.database) {
    throw new Error(
      "Connected database is not the isolated Android staging database",
    );
  }
  const existing = await client.query<{ table_name: string }>(
    `SELECT table_name FROM information_schema.tables
       WHERE table_schema='public' AND table_type='BASE TABLE'
       ORDER BY table_name`,
  );
  if (existing.rows.length) {
    throw new Error("Android staging seed requires an empty public schema");
  }
}

export async function inspectAndroidStagingSeed(
  database: Pick<Pool, "connect">,
) {
  const client = await database.connect();
  try {
    await requireEmptyDatabase(client);
    return {
      readyToApply: true,
      project: ANDROID_STAGING_SEED.project,
      database: ANDROID_STAGING_SEED.database,
      canonicalTables: [...canonicalTables],
      syntheticSipUri: `sip:${ANDROID_STAGING_SEED.extension}@${ANDROID_STAGING_SEED.domain}`,
      sipTransport: ANDROID_STAGING_SEED.transport,
      sipPort: ANDROID_STAGING_SEED.port,
      createsSession: false,
      createsPushDevice: false,
      createsWakeBinding: false,
    };
  } finally {
    client.release();
  }
}

export async function applyAndroidStagingSeed(
  database: Pick<Pool, "connect">,
  config: AndroidStagingSeedConfig,
) {
  if (!config.apply)
    throw new Error("Android staging seed is plan-only without --apply");
  const client = await database.connect();
  try {
    await client.query("BEGIN");
    await client.query(
      "SET LOCAL lock_timeout='5s'; SET LOCAL statement_timeout='30s'",
    );
    await client.query("SELECT pg_advisory_xact_lock(7101, 20260914)");
    await requireEmptyDatabase(client);
    await client.query(canonicalAuthoritySchemaSql);

    const sipPassword = randomBytes(32).toString("base64url");
    const digest = (identity: string) =>
      createHash("md5")
        .update(`${identity}:${ANDROID_STAGING_SEED.domain}:${sipPassword}`)
        .digest("hex");
    const ha1 = digest(ANDROID_STAGING_SEED.extension);
    const ha1b = digest(
      `${ANDROID_STAGING_SEED.extension}@${ANDROID_STAGING_SEED.domain}`,
    );

    await client.query(
      "INSERT INTO organizations(id,name,plan) VALUES($1,$2,$3)",
      [ANDROID_STAGING_SEED.organizationId, "Phone11 Android Staging", "lab"],
    );
    await client.query(
      "INSERT INTO tenants(id,name,plan,status) VALUES($1,$2,$3,'active')",
      [ANDROID_STAGING_SEED.tenantId, "Phone11 Android Staging", "lab"],
    );
    await client.query(
      `INSERT INTO users(id,"openId",name,email,"loginMethod",role)
       VALUES($1,$2,$3,$4,'phone11','user')`,
      [
        ANDROID_STAGING_SEED.userId,
        "phone11:staging:android:7101",
        "Phone11 Android Staging 7101",
        config.email,
      ],
    );
    await client.query("SELECT setval('users_id_seq', $1, true)", [
      ANDROID_STAGING_SEED.userId,
    ]);
    await client.query(
      `INSERT INTO extensions
       (id,org_id,tenant_id,user_id,extension_number,display_name,type,sip_username,sip_domain,
        transport,status,voicemail_enabled)
       VALUES($1,$2,$3,$4,$5,$6,'user',$5,$7,$8,'active',false)`,
      [
        ANDROID_STAGING_SEED.extensionId,
        ANDROID_STAGING_SEED.organizationId,
        ANDROID_STAGING_SEED.tenantId,
        ANDROID_STAGING_SEED.userId,
        ANDROID_STAGING_SEED.extension,
        "Android Staging 7101",
        ANDROID_STAGING_SEED.domain,
        ANDROID_STAGING_SEED.transport,
      ],
    );
    await client.query(
      "INSERT INTO user_extensions(user_id,extension_id,is_primary) VALUES($1,$2,true)",
      [ANDROID_STAGING_SEED.userId, ANDROID_STAGING_SEED.extensionId],
    );
    await client.query(
      `INSERT INTO sip_accounts
       (tenant_id,org_id,extension_id,user_id,sip_username,sip_domain,ha1,ha1b,transport_preference,status)
       VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9,'active')`,
      [
        ANDROID_STAGING_SEED.tenantId,
        ANDROID_STAGING_SEED.organizationId,
        ANDROID_STAGING_SEED.extensionId,
        ANDROID_STAGING_SEED.userId,
        ANDROID_STAGING_SEED.extension,
        ANDROID_STAGING_SEED.domain,
        ha1,
        ha1b,
        ANDROID_STAGING_SEED.transport,
      ],
    );
    await client.query(
      `INSERT INTO subscriber(username,domain,password,ha1,ha1b,email_address)
       VALUES($1,$2,$3,$4,$5,$6)`,
      [
        ANDROID_STAGING_SEED.extension,
        ANDROID_STAGING_SEED.domain,
        sipPassword,
        ha1,
        ha1b,
        config.email,
      ],
    );
    const proof = await client.query<{ count: number }>(`
      SELECT count(*)::integer AS count
        FROM users u
        JOIN user_extensions ue ON ue.user_id=u.id
        JOIN extensions e ON e.id=ue.extension_id AND e.user_id=u.id
        JOIN tenants t ON t.id=e.tenant_id AND t.status='active'
        JOIN sip_accounts sa ON sa.extension_id=e.id AND sa.tenant_id=t.id
        JOIN subscriber sub ON sub.username=sa.sip_username AND lower(sub.domain)=lower(sa.sip_domain)
       WHERE u.id=1 AND u.role='user' AND e.id=7101 AND e.extension_number='7101'
         AND e.status='active' AND e.deleted_at IS NULL AND ue.is_primary
         AND sa.status='active' AND sa.deleted_at IS NULL
         AND e.transport='UDP' AND sa.transport_preference='UDP'
         AND ('sip:'||sa.sip_username||'@'||lower(sa.sip_domain))='sip:7101@sip.stage.phone11.test'
         AND length(sub.password)>0
    `);
    if (proof.rows[0]?.count !== 1)
      throw new Error("Synthetic Android staging authority proof failed");
    await client.query("COMMIT");
    return {
      seeded: true,
      userId: ANDROID_STAGING_SEED.userId,
      tenantId: ANDROID_STAGING_SEED.tenantId,
      extensionId: ANDROID_STAGING_SEED.extensionId,
      sipUri: `sip:${ANDROID_STAGING_SEED.extension}@${ANDROID_STAGING_SEED.domain}`,
    };
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
