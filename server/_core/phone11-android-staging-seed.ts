export type AndroidStagingSeedConfig = {
  apply: boolean;
  email: string;
};

const emailSchema = z.email().transform((value) => value.trim().toLowerCase());

export function readAndroidStagingSeedConfig(input: {
  apply?: boolean;
  confirmEmptyDatabase?: boolean;
  project?: string;
  instance?: string;
  database?: string;
  extension?: string;
  domain?: string;
  email?: string;
}): AndroidStagingSeedConfig {
  const exact = (
    actual: string | undefined,
    expected: string,
    label: string,
  ) => {
    if (actual !== expected)
      throw new Error(`Android staging seed ${label} mismatch`);
  };
  exact(input.project, ANDROID_STAGING_SEED.project, "project");
  exact(input.instance, ANDROID_STAGING_SEED.instance, "instance");
  exact(input.database, ANDROID_STAGING_SEED.database, "database");
  exact(input.extension, ANDROID_STAGING_SEED.extension, "extension");
  exact(input.domain, ANDROID_STAGING_SEED.domain, "domain");
  const email = emailSchema.parse(input.email);
  if (input.apply && input.confirmEmptyDatabase !== true) {
    throw new Error(
      "Android staging seed apply requires --confirm-empty-database",
    );
  }
  return { apply: input.apply === true, email };
}

